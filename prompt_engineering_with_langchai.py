map_prompt = PromptTemplate(
    input_variables =['document'],
    template = """
    You are given a document chunk. summarize the core meaning consisely.

    Document:
    {document}

    Summary:
    """
)

reduce_prompt = PromptTemplate(
    input_variables=["summaries","question"],
    template="""
    You are given multiple summaries. use them to answer the question
    if the answer is not contained in the summaries, say "No Answer is Available"
    Summaries:
   {summaries}

   Question:
   {question}

   Answer:
    """
)

def map_reduce_chain(docs, question):
  summaries = []
  for doc in docs:
    summaries.append(chat.invoke(map_prompt.format(document=doc.page_content)).text.strip())
  return chat.invoke(reduce_prompt.format(summaries = summaries , question = question)).text.strip()

