from langchain_core.messages import trim_messages

selected_messages = trim_messages(
    history.messages,
    token_counter=len,  # <-- len will simply count the number of messages rather than tokens
    max_tokens=3,  # <-- allow up to 2 messages.
    strategy="last",
    # Most chat models expect that chat history starts with either:
    # (1) a HumanMessage or
    # (2) a SystemMessage followed by a HumanMessage
    # start_on="human" makes sure we produce a valid chat history
    start_on="human",
    # Usually, we want to keep the SystemMessage
    # if it's present in the original history.
    # The SystemMessage has special instructions for the model.
    include_system=True,
    allow_partial=False,
)

for msg in selected_messages:
    msg.pretty_print()

from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.messages import HumanMessage, AIMessage
from langgraph.graph import StateGraph, END

gemini_api_key = gemini_api_key

model = ChatGoogleGenerativeAI(
    model="gemini-2.5-flash-lite",
    google_api_key=gemini_api_key,
    temperature=0.7,
)

# --- STEP 1: Define the state ---
from typing import List, TypedDict

class State(TypedDict):
    messages: List
    summary: str

# --- STEP 2: Define your summarization reducer ---
def summarize_conversation(state: State):
    summary = state.get("summary", "")
    if summary:
        summary_message = (
            f"This is a summary of the conversation so far: {summary}\n\n"
            "Extend the summary by considering the new messages above."
        )
    else:
        summary_message = "Create a summary of the conversation above."

    # Add the summarization instruction to the messages
    messages = state["messages"] + [HumanMessage(content=summary_message)]
    response = model.invoke(messages)

    # Keep the last 2 messages and store new summary
    return {
        "summary": response.content,
        "messages": state["messages"][-2:]  # keep short memory
    }

# --- STEP 3: Define the main conversation node ---
def chat_node(state: State):
    response = model.invoke(state["messages"])
    return {"messages": state["messages"] + [response]}

# --- STEP 4: Build the graph ---
graph = StateGraph(State)

graph.add_node("chat", chat_node)
graph.add_node("summarize", summarize_conversation)
graph.add_edge("chat", "summarize")
graph.add_edge("summarize", END)

graph.set_entry_point("chat")

app = graph.compile()

# --- STEP 5: Run the conversation ---
state = {"messages": [HumanMessage(content="List 3 places to visit in Paris.")], "summary": ""}

state = app.invoke(state)
print("Bot:", state["messages"][-1].content)
print("Summary:", state["summary"])

# Continue conversation
state["messages"].append(HumanMessage(content="Which one of them has a lake view?"))
state = app.invoke(state)

print("\nBot:", state["messages"][-1].content)
print("Updated summary:", state["summary"])

