"""## 12.3 Refine chain (LCEL 2025)

---


"""

initial_prompt = PromptTemplate(
    input_variables = ["document", "question"],
    template="""
    Answer the following question using the provided document,

    Document:
    {document}

    Question:
    {question}

    Answer:
    """
)

refine_prompt = PromptTemplate(
    input_variables = ["existing_answer", "document", "question"],
    template="""
    We have an exsiting answer:
    {existing_answer}

    Here is new information from another document:
    {document}

    Question:
    {question}

    Refine the existing answer to include this ew information
    If the new document does not add anything, keep the answer unchanged

    Refined Answer:
    """
)

def refine_chain(docs, question):
  # initial step (given best match doc)
  answer = chat.invoke(initial_prompt.format(document=docs[0].page_content, question=question)).text.strip()
  # refine step (given rest of docs)
  for doc in docs[1:]:
    answer =  chat.invoke(refine_prompt.format(existing_answer=answer,
                                                        document=doc.page_content,
                                                        question=question)).text.strip()
  return answer

question = "what did Tesla invent?"

similar_docs = vector_db.similarity_search(question, k=2)

answer = refine_chain(similar_docs, question)
print(answer)

